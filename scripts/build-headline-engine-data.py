"""Builds lib/engine/agents/headline-engine-data.ts from the headline-engine skill's references.

Usage: python3 -I scripts/build-headline-engine-data.py <skill>/references lib/engine/agents/headline-engine-data.ts

Keeps the 20 formulas and, per archetype, the six strongest carousel and image covers that
follow the house rules: no emojis, no BREAKING:, no ellipsis, em dash or "exciting"/"amazing",
and at most one time-window headline ("24 HOURS SINCE ..."), because a model trained on
those winners learned to stamp time windows on every story.
"""
import json
import re
import sys

refs, out = sys.argv[1], sys.argv[2]
pattern_db = open(f"{refs}/headline_pattern_database.md", encoding="utf8").read()
winners_md = open(f"{refs}/proven_winners.md", encoding="utf8").read()

formulas = []
for block in re.split(r"\n### FORMULA ", pattern_db)[1:]:
    head = block.split("\n", 1)[0]
    match = re.match(r"(\d+): (.+)", head)
    if not match:
        continue
    pattern = re.search(r"\*\*Pattern\*\*: (.+)", block)
    use = re.search(r"\*\*Use when\*\*: (.+)", block)
    formulas.append({
        "n": int(match.group(1)),
        "name": match.group(2).strip().title(),
        "pattern": pattern.group(1).strip() if pattern else "",
        "use": use.group(1).strip() if use else "",
    })

EMOJI = re.compile("[\U0001F000-\U0001FAFF☀-➿️]")
TIME_WINDOW = re.compile(
    r"\b(\d+|ONE|TWO|THREE|A FEW)\s+(HOURS?|DAYS?|WEEKS?)\b.*\b(SINCE|AGO|AFTER)\b"
    r"|\bLESS THAN \d+ HOURS AGO\b|\bJUST \d+ (HOURS?|DAYS?) AFTER\b|\bHAS ONLY BEEN OUT FOR\b",
    re.I,
)
archetypes = {}
for section in re.split(r"\n## ", winners_md)[1:]:
    name = re.match(r"([A-Z/ ]+?) \(\d+\)", section)
    if not name:
        continue
    covers = section.split("**Carousel and image covers**", 1)
    if len(covers) < 2:
        continue
    body = covers[1].split("**Reel", 1)[0]
    picked, windows = [], 0
    for line in body.splitlines():
        match = re.match(r"- (.+) \((\d+(?:\.\d+)?)x, ([\w.]+), (\w+ \d{4})\)$", line.strip())
        if not match:
            continue
        text = match.group(1).strip()
        if EMOJI.search(text) or re.search(r"\bBREAKING\b", text) or "..." in text or "…" in text or "—" in text or text.count("!") > 1:
            continue
        if re.search(r"\b(EXCITING|AMAZING)\b", text, re.I):
            continue
        if TIME_WINDOW.search(text):
            if windows >= 1:
                continue
            windows += 1
        picked.append({"text": text.rstrip("."), "x": float(match.group(2)), "page": match.group(3), "when": match.group(4)})
        if len(picked) >= 6:
            break
    archetypes[name.group(1).strip()] = picked

with open(out, "w", encoding="utf8") as file:
    file.write(
        "/**\n"
        " * Generated by scripts/build-headline-engine-data.py from Ivan's headline-engine skill\n"
        " * (references/headline_pattern_database.md and references/proven_winners.md): the 20\n"
        " * formulas, and per archetype the six strongest carousel covers that follow the house\n"
        " * rules. `x` is likes against that page's usual post. Don't edit by hand; regenerate.\n"
        " */\n"
    )
    file.write("export const HEADLINE_FORMULAS: readonly { n: number; name: string; pattern: string; use: string }[] = ")
    file.write(json.dumps(formulas, ensure_ascii=False, indent=2))
    file.write(";\n\nexport const PROVEN_COVERS: Readonly<Record<string, readonly { text: string; x: number; page: string; when: string }[]>> = ")
    file.write(json.dumps(archetypes, ensure_ascii=False, indent=2))
    file.write(";\n")
print(len(formulas), {key: len(value) for key, value in archetypes.items()})
