function validatedArguments(name, args) {
  if (!object(args)) throw new RpcError(-32602, "Tool arguments must be an object.");
  const definition = toolDefinitions().find((tool) => tool.name === name);
  if (!definition) throw new RpcError(-32602, `Unknown tool: ${name}`);
  const allowed = Object.keys(definition.inputSchema.properties);
  if (Object.keys(args).some((key) => !allowed.includes(key))) {
    throw new RpcError(-32602, "Tool arguments contain an unsupported field.");
  }
  for (const key of definition.inputSchema.required) {
    if (!Object.hasOwn(args, key)) throw new RpcError(-32602, `Missing required argument: ${key}`);
  }
  for (const key of ["deckId", "expectedHash", "operationId"]) {
    if (Object.hasOwn(args, key) && (typeof args[key] !== "string" || !args[key].trim() || args[key].length > 512)) {
      throw new RpcError(-32602, `${key} must be a nonempty string of at most 512 characters.`);
    }
  }
  if (Object.hasOwn(args, "operationId") && !/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(args.operationId)) {
    throw new RpcError(-32602, "operationId must be a UUID. Omit it to generate one.");
  }
  if (Object.hasOwn(args, "jobId") && (typeof args.jobId !== "string" || !/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(args.jobId))) {
    throw new RpcError(-32602, "jobId must be the UUID returned by engine_recreate_post.");
  }
  if (Object.hasOwn(args, "postId") && (typeof args.postId !== "string" || !/^post-[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(args.postId))) {
    throw new RpcError(-32602, "postId must be the post-… id returned by engine_recreate_post.");
  }
  if (POST_TOOLS.has(name) && !Object.hasOwn(args, "postId") && !Object.hasOwn(args, "jobId")) {
    throw new RpcError(-32602, "Pass the postId (or jobId) from engine_recreate_post.");
  }
  if (Object.hasOwn(args, "mode") && !MODES.includes(args.mode)) throw new RpcError(-32602, "mode must be exact, checkpoint or autopilot.");
  if (Object.hasOwn(args, "brandId") && (typeof args.brandId !== "string" || !/^[a-z0-9](?:[a-z0-9-]{0,46}[a-z0-9])?$/.test(args.brandId))) {
    throw new RpcError(-32602, "brandId must be a brand guide id from engine_list_brands.");
  }
  for (const key of ["version", "expectedVersion"]) {
    if (Object.hasOwn(args, key) && (!Number.isSafeInteger(args[key]) || args[key] < 1)) throw new RpcError(-32602, `${key} must be a version number.`);
  }
  if (Object.hasOwn(args, "guide") && (!object(args.guide) || typeof args.guide.id !== "string")) throw new RpcError(-32602, "guide must be an object with the guide's id. Read engine_get_brand for its shape.");
  if (name === "engine_save_brand" && Object.hasOwn(args, "note") && (typeof args.note !== "string" || args.note.length > 200)) throw new RpcError(-32602, "note must be text of at most 200 characters.");
  if (Object.hasOwn(args, "language") && args.language !== "en" && args.language !== "es") throw new RpcError(-32602, "language must be en or es.");
  for (const key of ["templateId", "baseTemplateId"]) {
    if (Object.hasOwn(args, key) && (typeof args[key] !== "string" || !args[key].trim() || args[key].length > 200)) throw new RpcError(-32602, `${key} must be a template id of at most 200 characters.`);
  }
  if (name === "engine_check_deck" && Object.hasOwn(args, "deckId") === Object.hasOwn(args, "templateId")) throw new RpcError(-32602, "Pass either deckId or templateId.");
  if (Object.hasOwn(args, "stage") && !(name === "engine_recreate_submit_stage" ? SUBMITTABLE_STAGES : STAGES).includes(args.stage)) {
    throw new RpcError(-32602, `stage must be one of: ${(name === "engine_recreate_submit_stage" ? SUBMITTABLE_STAGES : STAGES).join(", ")}.`);
  }
  if (Object.hasOwn(args, "option") && (!Number.isSafeInteger(args.option) || args.option < 0 || args.option > 20)) throw new RpcError(-32602, "option must be the index of a headline option.");
  if (name === "engine_recreate_approve" && !Object.hasOwn(args, "option") && !Object.hasOwn(args, "headlineText")) throw new RpcError(-32602, "Pick a headline with option or write one in headlineText.");
  if (Object.hasOwn(args, "choice") && !ANSWERS.includes(args.choice)) throw new RpcError(-32602, "choice must be proceed, stop or link.");
  if (name === "engine_recreate_answer_check" && Object.hasOwn(args, "note") && (typeof args.note !== "string" || args.note.length > 2000)) throw new RpcError(-32602, "note must be text of at most 2000 characters.");
  if (args.choice === "link" && (typeof args.link !== "string" || !/^https?:\/\/\S+$/i.test(args.link.trim()))) throw new RpcError(-32602, "With choice link, pass the story's original as an http(s) link in link.");
  for (const key of ["plan", "output"]) {
    if (Object.hasOwn(args, key) && !object(args[key])) throw new RpcError(-32602, `${key} must be an object. Read engine_playbook for its shape.`);
  }
  for (const [key, max] of [["profileId", 120], ["url", 2000], ["caption", 10000], ["notes", 2000], ["headlineText", 200], ["link", 2000], ["instructions", 2000]]) {
    if (Object.hasOwn(args, key) && (typeof args[key] !== "string" || !args[key].trim() || args[key].length > max)) {
      throw new RpcError(-32602, `${key} must be a nonempty string of at most ${max} characters.`);
    }
  }
  if (Object.hasOwn(args, "uploads") && (!Array.isArray(args.uploads) || !args.uploads.length || args.uploads.length > 20 ||
      args.uploads.some((item) => !object(item) || typeof item.dataUrl !== "string" || !item.dataUrl.startsWith("data:image/") ||
        Object.keys(item).some((key) => key !== "name" && key !== "dataUrl") || (item.name !== undefined && (typeof item.name !== "string" || item.name.length > 200))))) {
    throw new RpcError(-32602, "uploads must be 1–20 objects with a data:image dataUrl and an optional name.");
  }
  if (Object.hasOwn(args, "xPosts") && (!Array.isArray(args.xPosts) || !args.xPosts.length || args.xPosts.length > 8 ||
      args.xPosts.some((item) => typeof item !== "string" || !item.trim() || item.length > 300))) {
    throw new RpcError(-32602, "xPosts must be 1–8 links to posts on X.");
  }
  if (name === "engine_recreate_post" && !Object.hasOwn(args, "url") && !Object.hasOwn(args, "uploads")) {
    throw new RpcError(-32602, "Pass an Instagram url or slide uploads.");
  }
  for (const key of ["spec", "changes"]) {
    if (Object.hasOwn(args, key) && !object(args[key])) throw new RpcError(-32602, `${key} must be an object. Read engine_capabilities for its schema.`);
  }
  if (Object.hasOwn(args, "offset") && (!Number.isSafeInteger(args.offset) || args.offset < 0 || args.offset > 10000)) {
    throw new RpcError(-32602, "offset must be an integer from 0 through 10000.");
  }
  if (Object.hasOwn(args, "limit") && (!Number.isSafeInteger(args.limit) || args.limit < 1 || args.limit > 100)) {
    throw new RpcError(-32602, "limit must be an integer from 1 through 100.");
  }
  const result = { ...args };
  if (name === "engine_list_templates" || name === "engine_list_decks") {
    result.offset ??= 0;
    result.limit ??= 20;
  }
  if (name === "engine_create_deck" || name === "engine_update_deck") result.operationId ??= randomUUID();
  return result;
}

async function readResponse(response) {
  if (Number(response.headers.get("content-length")) > MAX_HTTP_BYTES) {
    await response.body?.cancel();
    throw new ApiError("Engine response exceeds the bridge's 32 MiB limit.", response.status);
  }
  const chunks = [];
  let size = 0;
  if (response.body) {
    for await (const chunk of response.body) {
      size += chunk.byteLength;
      if (size > MAX_HTTP_BYTES) throw new ApiError("Engine response exceeds the bridge's 32 MiB limit.", response.status);
      chunks.push(chunk);
    }
  }
  try {
    return JSON.parse(Buffer.concat(chunks, size).toString("utf8"));
  } catch {
    throw new ApiError(`Engine returned invalid JSON (HTTP ${response.status}).`, response.status);
  }
}

function bridge(config) {
  let initialized = false;
  let capabilities;
  const redact = (value) => String(value).replaceAll(config.token, "[redacted]");
  async function api(action, args = {}) {
    return send({ url: config.endpoint, method: "POST", body: { action, ...args } }, action);
  }
  async function send(route, action) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), HTTP_TIMEOUT_MS);
    try {
      const response = await fetch(route.url, {
        method: route.method,
        headers: { ...(route.body ? { "content-type": "application/json" } : {}), authorization: `Bearer ${config.token}` },
        ...(route.body ? { body: JSON.stringify(route.body) } : {}),
        redirect: "error",
        signal: controller.signal,
      });
      const value = await readResponse(response);
      if (!response.ok) {
        const reason = object(value) && value.error ? (typeof value.error === "string" ? value.error : JSON.stringify(value.error)) : "Request failed";
        throw new ApiError(`Engine HTTP ${response.status}: ${redact(reason).slice(0, 2048)}`, response.status);
      }
      if (!object(value)) throw new ApiError("Engine returned a response that is not a JSON object.", response.status);
      if (action === "capabilities") capabilities = value;
      return value;
    } catch (error) {
      if (error instanceof ApiError) throw error;
      throw new ApiError(controller.signal.aborted ? "Engine request timed out after 30 seconds. Its outcome may be unknown; reuse operationId for any identical mutation retry." : "Could not reach Engine. Check ENGINE_URL and that the server is running. Redirects are refused. A mutation may have completed; reuse operationId for an identical retry.");
    } finally {
      clearTimeout(timer);
    }
  }
  function toolResult(value, isError = false) {
    const safe = JSON.parse(redact(JSON.stringify(value)));
    return { content: [{ type: "text", text: JSON.stringify(safe) }], structuredContent: safe, isError };
  }
  return async function dispatch(message) {
    if (!object(message) || message.jsonrpc !== "2.0" || typeof message.method !== "string" ||
        (Object.hasOwn(message, "id") && !(typeof message.id === "string" || (typeof message.id === "number" && Number.isFinite(message.id))))) {
      throw new RpcError(-32600, "Invalid JSON-RPC request.");
    }
    const notification = !Object.hasOwn(message, "id");
    if (notification) return undefined;
    const params = message.params === undefined ? {} : message.params;
    if (!object(params)) throw new RpcError(-32602, "Request params must be an object.");
    if (message.method === "ping") return {};
    if (message.method === "initialize") {
      if (initialized) throw new RpcError(-32600, "This connection is already initialized.");
      if (typeof params.protocolVersion !== "string" || !object(params.capabilities) ||
          !object(params.clientInfo) || typeof params.clientInfo.name !== "string" || typeof params.clientInfo.version !== "string") {
        throw new RpcError(-32602, "initialize requires protocolVersion, capabilities, and clientInfo with name and version.");
      }
      initialized = true;
      return {
        protocolVersion: PROTOCOL_VERSIONS.includes(params.protocolVersion) ? params.protocolVersion : PROTOCOL_VERSIONS[0],
        capabilities: { tools: {} },
        serverInfo: { name: "engine-slides", title: "Engine editable slides", version: "1.0.0" },
        instructions: "Start with engine_capabilities for the live deck and update schemas, coordinates, fonts, and limits. Create independent native layers; use the returned editorUrl to let a person continue editing. Get the current hash before updating. Preserve operationId for any identical mutation retry. To recreate an Instagram post for one of the team's pages, call engine_list_page_profiles, then engine_recreate_post, then poll engine_recreate_status. mode exact rebuilds a post as it is, with nothing added; the check may pause a run to ask (engine_recreate_answer_check, on a person's word); with mode checkpoint the run pauses for engine_recreate_approve (engine_recreate_add_posts adds posts from X by link first); engine_recreate_rerun_stage redoes one stage with instructions, and engine_recreate_submit_stage hands in a stage you did yourself (read engine_playbook first). Before designing or writing for a brand, read its guide with engine_get_brand (its brief is the guide in plain words); check your deck with engine_check_deck; draft a template from a guide with engine_design_template. Save guide edits with engine_save_brand (every save is a version; engine_restore_brand undoes one).",
      };
    }
    if (!initialized) throw new RpcError(-32000, "Initialize the MCP connection before requesting tools.");
    if (message.method === "tools/list") {
      if (params.cursor !== undefined) throw new RpcError(-32602, "This server returns all tools in one page; omit cursor.");
      if (!capabilities) {
        try { await api("capabilities"); } catch { /* Keep diagnostics tools discoverable when Engine is offline. */ }
      }
      return { tools: toolDefinitions(capabilities) };
    }
    if (message.method === "tools/call") {
      if (typeof params.name !== "string") throw new RpcError(-32602, "tools/call requires a tool name.");
      const args = validatedArguments(params.name, params.arguments === undefined ? {} : params.arguments);
      try {
        const value = ROUTES[params.name] ? await send(ROUTES[params.name](config, args)) : await api(ACTIONS[params.name], args);
        return toolResult(args.operationId ? { ...value, operationId: args.operationId } : value);
      } catch (error) {
        return toolResult({ error: error.message, ...(error.status ? { status: error.status } : {}), ...(args.operationId ? { operationId: args.operationId } : {}) }, true);
      }
    }
    throw new RpcError(-32601, "Method not found.");
  };
}

async function main() {
  const dispatch = bridge(configuration());
  async function write(value) {
    let line = JSON.stringify(value);
    if (Buffer.byteLength(line) > MAX_OUTPUT_BYTES) line = JSON.stringify({ jsonrpc: "2.0", id: value.id, error: { code: -32603, message: "Response exceeds the bridge's output limit." } });
    await new Promise((resolve, reject) => process.stdout.write(`${line}\n`, (error) => error ? reject(error) : resolve()));
  }
  async function receive(line) {
    if (!line.length) return;
    let message;
    try {
      message = JSON.parse(line.toString("utf8"));
    } catch {
      await write({ jsonrpc: "2.0", id: null, error: { code: -32700, message: "Parse error." } });
      return;
    }
    try {
      const result = await dispatch(message);
      if (result !== undefined) await write({ jsonrpc: "2.0", id: message.id, result });
    } catch (error) {
      const id = object(message) && (typeof message.id === "string" || (typeof message.id === "number" && Number.isFinite(message.id))) ? message.id : null;
      await write({ jsonrpc: "2.0", id, error: { code: error instanceof RpcError ? error.code : -32603, message: error instanceof RpcError ? error.message : "Internal error." } });
    }
  }
  let fragments = [];
  let size = 0;
  let oversized = false;
  for await (const chunk of process.stdin) {
    let start = 0;
    while (start < chunk.length) {
      const newline = chunk.indexOf(10, start);
      const part = chunk.subarray(start, newline === -1 ? chunk.length : newline);
      if (!oversized) {
        size += part.length;
        if (size > MAX_INPUT_BYTES) {
          oversized = true;
          fragments = [];
        } else fragments.push(part);
      }
      if (newline === -1) break;
      if (oversized) await write({ jsonrpc: "2.0", id: null, error: { code: -32600, message: "Message exceeds the bridge's 16 MiB input limit." } });
      else await receive(Buffer.concat(fragments, size));
      fragments = [];
      size = 0;
      oversized = false;
      start = newline + 1;
    }
  }
  if (oversized) await write({ jsonrpc: "2.0", id: null, error: { code: -32600, message: "Message exceeds the bridge's 16 MiB input limit." } });
  else if (size) await receive(Buffer.concat(fragments, size));
}

main().catch((error) => {
  if (error.code !== "EPIPE") process.stderr.write(`Engine MCP: ${error.message}\n`);
  process.exitCode = 1;
});
