function object(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function configuration() {
  let url;
  try {
    url = new URL(process.env.ENGINE_URL || "http://localhost:3000");
  } catch {
    throw new Error("ENGINE_URL must be an absolute HTTPS URL or a loopback HTTP URL.");
  }
  const loopback = url.hostname === "localhost" || url.hostname === "[::1]" ||
    (isIP(url.hostname) === 4 && url.hostname.startsWith("127."));
  if (url.username || url.password || url.search || url.hash ||
      (url.protocol !== "https:" && !(url.protocol === "http:" && loopback))) {
    throw new Error("ENGINE_URL must use HTTPS (HTTP is allowed only on loopback), with no credentials, query, or fragment.");
  }
  const token = process.env.ENGINE_AGENT_TOKEN?.trim();
  if (!token || token.length > 4096 || /[\r\n]/.test(token)) {
    throw new Error("Set ENGINE_AGENT_TOKEN to an agent access token from Engine's Agent access panel.");
  }
  return { endpoint: new URL("/api/agent/slides", url), recreate: new URL("/api/engine/recreate", url), profiles: new URL("/api/engine/page-profiles", url), brands: new URL("/api/engine/brands", url), token };
}

